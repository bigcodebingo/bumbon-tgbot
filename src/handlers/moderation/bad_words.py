import re

# Две основы и явно перечисленные окончания: «ублюдок», «ублюдком»,
# «выблядки», «ублюдочный» и т. п. Произвольные производные и замены букв
# не распознаются. Границы слова не дают совпасть части более длинного слова.
INSULT = re.compile(
    r"\b(?:ублюд|выбляд)(?:ок|к(?:а|у|ом|е|и|ов|ам|ами|ах)"
    r"|очн(?:ый|ая|ое|ые|ого|ой|ому|ую|ым|ыми|ых))\b"
)

# Участки в парных кавычках исключаются из проверки. Для прямых двойных
# и одинарных кавычек совпадение ограничено одной строкой. Само наличие
# кавычек не доказывает цитирование: это правило можно использовать для обхода.
QUOTES = re.compile(r'«[^»]*»|“[^”]*”|„[^“]*“|"[^"\n]*"|\'[^\'\n]*\'')

# Маркеры чужой речи и обсуждения слов: «Сава говорит ты ублюдок»,
# «он назвал меня ублюдком». Совпадение пропускает всё сообщение,
# даже если маркер не относится к оскорблению.
REPORT = re.compile(
    r"\b(?:говорит|говорят|говорил[аи]?|сказал[аи]?|сказали|назвал[аи]?|назвали"
    r"|называ(?:ет|ют|ешь|ете|л[аи]?)|цитата|цитирую|пересказ|например)\b"
    r"|\b(?:не\s+(?:называй|называйте|говори|говорите)|слово|фраза)\b"
)

# Признаки рассказа в текущем сообщении и недавних репликах автора.
# Например, «я помню» помогает пропустить историю, отправленную частями.
STORY = re.compile(
    r"\b(?:я\s+помню|помнишь|помните|вспомнил[аи]?|однажды|история"
    r"|в\s+(?:фильме|книге|сериале))\b"
)

# Местоимения второго лица — признак обращения, но не доказательство того,
# что оскорбительное слово относится к этому обращению.
ADDRESS = re.compile(r"\b(?:ты|тебя|тебе|тобой|вы|вас|вам|вами)\b")

# Повелительные формы для обращений без «ты»: «завали ебало выблядок».
# Сами по себе эти слова не считаются нарушением: нужен также INSULT.
IMPERATIVE = re.compile(
    r"\b(?:пошел|пошла|пошли|пошли-ка|иди|идите|завали|завалите"
    r"|заткнись|заткнитесь|закрой|закройте)\b"
)

# Проверка остатка после удаления оскорблений: если символов слова больше
# нет, фрагмент считается отдельным оскорблением. Цифры и «_» тоже входят в \w.
WORD = re.compile(r"\w+", re.UNICODE)

# Проверяется конец текста перед найденным оскорблением: «я ублюдок»,
# «он такой ублюдок». $ означает конец проверяемой строки. Такие совпадения
# исключаются; относится ли «он» к участнику чата, правило не устанавливает.
OTHER_SUBJECT = re.compile(
    r"\b(?:я|мы|он|она|они|это)(?:\s+(?:же|просто|такой|такая|такие))?[\s,]*$"
)

# Разделение сообщения на фрагменты по знакам завершения фразы и переносу
# строки. Запятая и двоеточие разделителями не являются.
CLAUSE_SEPARATOR = re.compile(r"[.!?;\n]+")

# Непосредственное отрицание оскорбления: «не ублюдок», «никакой выблядок».
# Оскорбление с отрицанием исключается до проверки направленности.
NEGATED_INSULT = re.compile(r"\b(?:не|никакой)\s+(?:" + INSULT.pattern + r")")
